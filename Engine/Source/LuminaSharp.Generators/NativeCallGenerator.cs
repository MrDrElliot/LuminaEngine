using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using LuminaSharp.ScriptProperties;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace LuminaSharp.Generators;

// Writes the marshalled P/Invoke body of each [NativeCall] partial method, matching the Reflector's C++ thunk ABI.
[Generator]
public sealed class NativeCallGenerator : IIncrementalGenerator
{
    private const string AttributeMetadataName = "LuminaSharp.NativeCallAttribute";
    private const string DefaultModule = "LuminaNative";
    private const string EntityType = "global::LuminaSharp.FEntity";
    private const int Utf8ScratchBytes = 256;

    private static readonly DiagnosticDescriptor NoSelf = new(
        id: "LUM0301",
        title: "Instance [NativeCall] has nothing to pass as self",
        messageFormat: "[NativeCall] '{0}' is an instance method, but '{1}' has no Handle member and is not a mutable unmanaged struct. Make it static or give the type a Handle.",
        category: "LuminaSharp",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor Overloaded = new(
        id: "LUM0302",
        title: "Overloaded [NativeCall] name",
        messageFormat: "[NativeCall] '{0}' is declared more than once in '{1}', and its generated binding is named after the method. Give each one its own name.",
        category: "LuminaSharp",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor ByRefParameter = new(
        id: "LUM0303",
        title: "[NativeCall] parameter passed by reference",
        messageFormat: "[NativeCall] '{0}' takes '{1}' by ref, in or out, which the binding cannot marshal. Pass it by value, or as a pointer or Span.",
        category: "LuminaSharp",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor Unreopenable = new(
        id: "LUM0306",
        title: "[NativeCall] the generated body cannot be placed",
        messageFormat: "[NativeCall] '{0}' cannot get a generated body because '{1}' is generic or not partial. Keep the method non-generic and every type around it partial and non-generic.",
        category: "LuminaSharp",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private const string AttributeSource = @"// <auto-generated/>
#nullable enable
namespace LuminaSharp
{
    /// <summary>
    /// Marks a <c>partial</c> method whose body is generated as a native binding. Module defaults to
    /// ""LuminaNative""; entry point defaults to ""LuminaSharp_"" + the method name. Instance methods
    /// pass the object Handle as the first native argument.
    /// </summary>
    [global::System.AttributeUsage(global::System.AttributeTargets.Method)]
    internal sealed class NativeCallAttribute : global::System.Attribute
    {
        public NativeCallAttribute() { }
        public NativeCallAttribute(string entryPoint) { EntryPoint = entryPoint; }
        public string? Module { get; set; }
        public string? EntryPoint { get; set; }

        /// <summary>Skip the GC-mode switch on the call. Only valid for a short, non-blocking native leaf that
        /// never re-enters managed, blocks, or runs long; otherwise it can stall or deadlock the GC.</summary>
        public bool SuppressGCTransition { get; set; }
    }
}
";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx =>
            ctx.AddSource("NativeCallAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

        IncrementalValuesProvider<Model?> models = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeMetadataName,
            predicate: static (node, _) => node is MethodDeclarationSyntax m
                && m.Modifiers.Any(t => t.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.PartialKeyword)),
            transform: static (ctx, ct) => BuildModel(ctx, ct));

        IncrementalValueProvider<ImmutableArray<Model?>> collected = models.Collect();

        context.RegisterSourceOutput(collected, static (spc, all) => Emit(spc, all));
    }

    private sealed record Model(string Namespace, string TypePath, string TypeHeaders, string Member, Diagnostic? Error = null);

    private static Model Refuse(DiagnosticDescriptor rule, IMethodSymbol method, string subject)
    {
        return new Model(string.Empty, string.Empty, string.Empty, string.Empty,
            Diagnostic.Create(rule, method.Locations.FirstOrDefault(), method.Name, subject));
    }

    private enum Kind { Pass, String, SoftPath, Bool, Enum, Entity, Array }

    private static Model? BuildModel(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
    {
        if (ctx.TargetSymbol is not IMethodSymbol method)
        {
            return null;
        }

        INamedTypeSymbol type = method.ContainingType;
        if (ScriptPropertyClassifier.HasAttributedTwin(method, AttributeMetadataName))
        {
            return Refuse(Overloaded, method, type.Name);
        }
        IParameterSymbol? byRef = method.Parameters.FirstOrDefault(p => p.RefKind != RefKind.None);
        if (byRef != null)
        {
            return Refuse(ByRefParameter, method, byRef.Name);
        }
        if (method.IsGenericMethod)
        {
            return Refuse(Unreopenable, method, method.Name);
        }
        for (INamedTypeSymbol? container = type; container != null; container = container.ContainingType)
        {
            if (container.IsGenericType || !container.DeclaringSyntaxReferences.All(r =>
                    r.GetSyntax(ct) is TypeDeclarationSyntax d && d.Modifiers.Any(Microsoft.CodeAnalysis.CSharp.SyntaxKind.PartialKeyword)))
            {
                return Refuse(Unreopenable, method, container.Name);
            }
        }

        // The entry point may come from the constructor argument or the named property.
        string? module = null;
        string? entry = null;
        bool suppressGCTransition = false;
        AttributeData attr = ctx.Attributes[0];
        if (attr.ConstructorArguments.Length == 1 && attr.ConstructorArguments[0].Value is string ctorEntry)
        {
            entry = ctorEntry;
        }
        foreach (KeyValuePair<string, TypedConstant> named in attr.NamedArguments)
        {
            if (named.Key == "Module" && named.Value.Value is string m)
            {
                module = m;
            }
            else if (named.Key == "EntryPoint" && named.Value.Value is string e)
            {
                entry = e;
            }
            else if (named.Key == "SuppressGCTransition" && named.Value.Value is bool s)
            {
                suppressGCTransition = s;
            }
        }
        module ??= DefaultModule;
        entry ??= "LuminaSharp_" + method.Name;

        SymbolDisplayFormat fq = SymbolDisplayFormat.FullyQualifiedFormat;

        var nativeTypes = new List<string>();
        var callArgs = new List<string>();
        var stringParams = new List<(int Index, string Name)>();
        var spanParams = new List<(int Index, string Name, string Elem)>();
        var sigParams = new List<string>();

        // Instance methods pass the containing type's Handle first, or for a value struct the pinned address of this.
        string? selfPin = null;
        if (!method.IsStatic)
        {
            string? handleTypeFq = FindHandleType(type, fq);
            if (handleTypeFq != null)
            {
                nativeTypes.Add(handleTypeFq);
                callArgs.Add("Handle");
            }
            else if (type.TypeKind == TypeKind.Struct && !type.IsReadOnly && type.IsUnmanagedType)
            {
                string selfFq = type.ToDisplayString(fq);
                nativeTypes.Add(selfFq + "*");
                callArgs.Add("__self");
                selfPin = "fixed (" + selfFq + "* __self = &this)";
            }
            else
            {
                return Refuse(NoSelf, method, type.Name);
            }
        }

        for (int i = 0; i < method.Parameters.Length; i++)
        {
            IParameterSymbol p = method.Parameters[i];
            string name = p.Name;
            string typeFq = p.Type.ToDisplayString(fq);
            sigParams.Add($"{typeFq} {name}");

            // A span crosses as its pinned element pointer followed by its length.
            if (TryGetSpanElement(p.Type, fq, out string spanElem))
            {
                nativeTypes.Add($"{spanElem}*");
                nativeTypes.Add("int");
                callArgs.Add($"__sp{i}");
                callArgs.Add($"{name}.Length");
                spanParams.Add((i, name, spanElem));
                continue;
            }

            // A struct handle crosses as the address it views.
            if (StructHandleOf(p.Type) != null)
            {
                nativeTypes.Add("global::System.IntPtr");
                callArgs.Add($"global::LuminaSharp.NativeStructs.AddressOf({name})");
                continue;
            }

            if (ScriptPropertyClassifier.IsNativeObject(p.Type))
            {
                nativeTypes.Add("global::System.IntPtr");
                callArgs.Add($"({name} is null ? global::System.IntPtr.Zero : {name}.Handle)");
                continue;
            }

            switch (Classify(p.Type, typeFq))
            {
                case Kind.String:
                    nativeTypes.Add("byte*");
                    nativeTypes.Add("int");
                    callArgs.Add($"__enc{i}");
                    callArgs.Add($"__len{i}");
                    stringParams.Add((i, name));
                    break;
                case Kind.SoftPath:
                    nativeTypes.Add("byte*");
                    nativeTypes.Add("int");
                    callArgs.Add($"__enc{i}");
                    callArgs.Add($"__len{i}");
                    stringParams.Add((i, name + ".GetPath()"));
                    break;
                case Kind.Bool:
                    // A bool crosses as a byte because the thunk takes an unsigned char.
                    nativeTypes.Add("byte");
                    callArgs.Add($"({name} ? (byte)1 : (byte)0)");
                    break;
                case Kind.Enum:
                    nativeTypes.Add("int");
                    callArgs.Add($"(int){name}");
                    break;
                case Kind.Entity:
                    nativeTypes.Add("uint");
                    callArgs.Add($"{name}.Id");
                    break;
                default:
                    nativeTypes.Add(typeFq);
                    callArgs.Add(name);
                    break;
            }
        }

        string retCs;
        System.Func<string, string> wrap = call => call;
        bool stringReturn = false;
        bool arrayReturn = false;
        string arrayElemFq = string.Empty;
        bool nativeRefReturn = false;
        string nativeRefRetType = string.Empty;
        string handleReturnBuild = string.Empty;
        bool arrayElemIsCObject = false;
        if (method.ReturnsVoid)
        {
            retCs = "void";
            nativeTypes.Add("void");
        }
        else if (ScriptPropertyClassifier.IsComponentRef(method.ReturnType))
        {
            retCs = method.ReturnType.ToDisplayString(fq);
            nativeRefReturn = true;
            // A component tracks its owner like a registry fetch, so a kept reference never reads a moved slot.
            handleReturnBuild = retCs + ".FromPointer(__p)";
            nativeTypes.Add("global::System.IntPtr");
        }
        else if (StructHandleOf(method.ReturnType) is INamedTypeSymbol handleRet)
        {
            string handleFq = handleRet.ToDisplayString(fq);
            retCs = method.ReturnType.ToDisplayString(fq);
            nativeRefReturn = true;
            handleReturnBuild = "global::LuminaSharp.NativeStructs.FromAddressOrNull<" + handleFq + ">(__p)";
            if (method.ReturnType.OriginalDefinition.SpecialType != SpecialType.System_Nullable_T)
            {
                handleReturnBuild += ".GetValueOrDefault()";
            }
            nativeTypes.Add("global::System.IntPtr");
        }
        else if (ScriptPropertyClassifier.IsNativeObject(method.ReturnType))
        {
            nativeRefRetType = method.ReturnType.ToDisplayString(fq);
            retCs = nativeRefRetType + "?";
            nativeRefReturn = true;
            nativeTypes.Add("global::System.IntPtr");
        }
        else
        {
            string retFq = method.ReturnType.ToDisplayString(fq);
            retCs = retFq;
            switch (Classify(method.ReturnType, retFq))
            {
                case Kind.String:
                    // The export fills a trailing caller buffer and returns the full byte length, so a short buffer means a second pass.
                    stringReturn = true;
                    nativeTypes.Add("byte*");   // trailing caller buffer
                    nativeTypes.Add("int");     // trailing buffer capacity
                    nativeTypes.Add("int");     // returned byte length
                    break;
                case Kind.Array:
                {
                    // The same two-pass buffer ABI as a string return, counted in elements rather than bytes.
                    arrayReturn = true;
                    ITypeSymbol arrayElem = ((IArrayTypeSymbol)method.ReturnType).ElementType;
                    arrayElemFq = arrayElem.ToDisplayString(fq);
                    // A CObject element crosses as its handle and is rebuilt managed-side, so its wire width is a pointer.
                    arrayElemIsCObject = ScriptPropertyClassifier.IsNativeObject(arrayElem);
                    nativeTypes.Add(arrayElemIsCObject ? "global::System.IntPtr*" : arrayElemFq + "*");
                    nativeTypes.Add("int");
                    nativeTypes.Add("int");
                    break;
                }
                case Kind.Bool:
                    // Reading only the low byte also works for a hand export that returns int.
                    nativeTypes.Add("byte");
                    wrap = call => $"{call} != 0";
                    break;
                case Kind.Enum:
                    nativeTypes.Add("int");
                    wrap = call => $"({retFq}){call}";
                    break;
                case Kind.Entity:
                    nativeTypes.Add("uint");
                    wrap = call => $"new {retFq}({call})";
                    break;
                default:
                    nativeTypes.Add(retFq);
                    break;
            }
        }

        // A direct P/Invoke the JIT inlines, where a stored function pointer costs an indirect call per crossing.
        string field = $"__pi_{method.Name}";
        string bound = $"__ok_{method.Name}";
        var externParams = new List<string>();
        for (int i = 0; i < nativeTypes.Count - 1; ++i)
        {
            externParams.Add(nativeTypes[i] + " __a" + i);
        }
        string coreArgs = string.Join(", ", callArgs);
        // The implementation repeats the declaration's modifiers, since a partial method without an access modifier must stay without one.
        IEnumerable<string> methodMods = ((MethodDeclarationSyntax)ctx.TargetNode).Modifiers
            .Where(t => !t.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.UnsafeKeyword))
            .Select(t => t.Text);
        string sig = $"{string.Join(" ", methodMods)} {retCs} {method.Name}({string.Join(", ", sigParams)})";

        var sb = new StringBuilder();
        string statField = $"__st_{method.Name}";
        string statCount = "if (global::LuminaSharp.InteropStats.Enabled) { ++global::LuminaSharp.InteropStats.Hits[" + statField + "]; }\n";
        sb.Append("        private static readonly int ").Append(statField).Append(" = global::LuminaSharp.InteropStats.Register(\"")
          .Append(type.Name).Append('.').Append(method.Name).Append("\");\n");
        sb.Append("        [global::System.Runtime.InteropServices.DllImport(\"").Append(module).Append("\", EntryPoint = \"").Append(entry)
          .Append("\", ExactSpelling = true, CallingConvention = global::System.Runtime.InteropServices.CallingConvention.Cdecl)]\n");
        if (suppressGCTransition)
        {
            sb.Append("        [global::System.Runtime.InteropServices.SuppressGCTransition]\n");
        }
        sb.Append("        private static extern ").Append(nativeTypes[nativeTypes.Count - 1]).Append(' ').Append(field)
          .Append('(').Append(string.Join(", ", externParams)).Append(");\n");
        // Read once and folded by the JIT, so the drift check costs nothing per call.
        sb.Append("        private static readonly bool ").Append(bound).Append(" = global::LuminaSharp.NativeBindings.Bind(\"")
          .Append(module).Append("\", \"").Append(entry).Append("\", ").Append(SignatureSum(nativeTypes))
          .Append(");\n");
        // Every scratch buffer below is written before it is read, so zeroing it would be wasted work on each call.
        if (stringParams.Count > 0 || stringReturn || arrayReturn)
        {
            sb.Append("        [global::System.Runtime.CompilerServices.SkipLocalsInit]\n");
        }
        // Only an inlined wrapper costs what a bare P/Invoke does, and only a stack scratch buffer keeps it from inlining.
        if (stringParams.Count == 0 && !stringReturn && !arrayReturn)
        {
            sb.Append("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]\n");
        }
        sb.Append("        ").Append(sig).Append('\n');

        static string Pad(int n) => new string(' ', n);

        // Runs inside the span pins, with every argument already marshalled into coreArgs.
        string CoreBody(int indent)
        {
            string pad = Pad(indent);
            if (stringReturn)
            {
                string prefix = callArgs.Count > 0 ? coreArgs + ", " : string.Empty;
                // An overflow copies what the native side stashed, and only an export that stashes nothing is called twice.
                return pad + "byte* __rb = stackalloc byte[" + Utf8ScratchBytes + "];\n"
                     + pad + "int __len = " + field + "(" + prefix + "__rb, " + Utf8ScratchBytes + ");\n"
                     + pad + "if (__len <= 0) { return string.Empty; }\n"
                     + pad + "if (__len <= " + Utf8ScratchBytes + ")\n" + pad + "{\n"
                     + pad + "    return global::LuminaSharp.Interop.GetString(__rb, __len);\n"
                     + pad + "}\n"
                     + pad + "byte[] __buf = new byte[__len];\n"
                     + pad + "fixed (byte* __bp = __buf)\n" + pad + "{\n"
                     + pad + "    int __w = global::LuminaSharp.NativeBindings.TakeCallOverflow(__rb, __bp, __len);\n"
                     + pad + "    if (__w < 0) { __w = " + field + "(" + prefix + "__bp, __len); }\n"
                     + pad + "    return global::LuminaSharp.Interop.GetString(__bp, __w < __len ? __w : __len);\n"
                     + pad + "}\n";
            }
            if (arrayReturn && arrayElemIsCObject)
            {
                string prefix = callArgs.Count > 0 ? coreArgs + ", " : string.Empty;
                string wrap = "global::LuminaSharp.Wrapper<" + arrayElemFq + ">.ForObject";
                // An element whose managed instance could not be rebuilt is dropped rather than left null.
                return pad + "int __cap = 1024 / global::System.IntPtr.Size;\n"
                     + pad + "global::System.IntPtr* __sb = stackalloc global::System.IntPtr[__cap];\n"
                     + pad + "int __len = " + field + "(" + prefix + "__sb, __cap);\n"
                     + pad + "if (__len <= 0) { return global::System.Array.Empty<" + arrayElemFq + ">(); }\n"
                     + pad + "global::System.IntPtr[] __raw;\n"
                     + pad + "int __w;\n"
                     + pad + "if (__len <= __cap)\n"
                     + pad + "{\n"
                     + pad + "    __raw = new global::System.IntPtr[__len];\n"
                     + pad + "    new global::System.ReadOnlySpan<global::System.IntPtr>(__sb, __len).CopyTo(__raw);\n"
                     + pad + "    __w = __len;\n"
                     + pad + "}\n"
                     + pad + "else\n"
                     + pad + "{\n"
                     + pad + "    __raw = new global::System.IntPtr[__len];\n"
                     + pad + "    fixed (global::System.IntPtr* __bp = __raw)\n"
                     + pad + "    {\n"
                     + pad + "        __w = global::LuminaSharp.NativeBindings.TakeCallOverflow(__sb, __bp, __len * global::System.IntPtr.Size);\n"
                     + pad + "        __w = __w < 0 ? " + field + "(" + prefix + "__bp, __len) : __w / global::System.IntPtr.Size;\n"
                     + pad + "    }\n"
                     + pad + "    if (__w > __len) { __w = __len; }\n"
                     + pad + "    if (__w < 0) { __w = 0; }\n"
                     + pad + "}\n"
                     + pad + "" + arrayElemFq + "[] __buf = new " + arrayElemFq + "[__w];\n"
                     + pad + "int __n = 0;\n"
                     + pad + "for (int __i = 0; __i < __w; ++__i)\n"
                     + pad + "{\n"
                     + pad + "    " + arrayElemFq + "? __e = " + wrap + "(__raw[__i]);\n"
                     + pad + "    if (__e is not null) { __buf[__n++] = __e; }\n"
                     + pad + "}\n"
                     + pad + "if (__n < __w) { global::System.Array.Resize(ref __buf, __n); }\n"
                     + pad + "return __buf;\n";
            }
            if (arrayReturn)
            {
                string prefix = callArgs.Count > 0 ? coreArgs + ", " : string.Empty;
                // An overflow copies what the native side stashed, and only an export that stashes nothing is called twice.
                return pad + "int __cap = 1024 / global::System.Runtime.CompilerServices.Unsafe.SizeOf<" + arrayElemFq + ">();\n"
                     + pad + "if (__cap < 1) { __cap = 1; }\n"
                     + pad + arrayElemFq + "* __sb = stackalloc " + arrayElemFq + "[__cap];\n"
                     + pad + "int __len = " + field + "(" + prefix + "__sb, __cap);\n"
                     + pad + "if (__len <= 0) { return global::System.Array.Empty<" + arrayElemFq + ">(); }\n"
                     + pad + "if (__len <= __cap)\n" + pad + "{\n"
                     + pad + "    " + arrayElemFq + "[] __fit = new " + arrayElemFq + "[__len];\n"
                     + pad + "    new global::System.ReadOnlySpan<" + arrayElemFq + ">(__sb, __len).CopyTo(__fit);\n"
                     + pad + "    return __fit;\n"
                     + pad + "}\n"
                     + pad + arrayElemFq + "[] __buf = new " + arrayElemFq + "[__len];\n"
                     + pad + "int __w;\n"
                     + pad + "fixed (" + arrayElemFq + "* __bp = __buf)\n" + pad + "{\n"
                     + pad + "    int __es = global::System.Runtime.CompilerServices.Unsafe.SizeOf<" + arrayElemFq + ">();\n"
                     + pad + "    __w = global::LuminaSharp.NativeBindings.TakeCallOverflow(__sb, __bp, __len * __es);\n"
                     + pad + "    __w = __w < 0 ? " + field + "(" + prefix + "__bp, __len) : __w / __es;\n"
                     + pad + "}\n"
                     // A count that grew between the calls is clamped, never read past the buffer.
                     + pad + "if (__w < __len) { global::System.Array.Resize(ref __buf, __w < 0 ? 0 : __w); }\n"
                     + pad + "return __buf;\n";
            }
            if (nativeRefReturn)
            {
                // An object return goes through the per-object wrapper cache, so a repeated getter keeps identity.
                string build = handleReturnBuild.Length > 0
                    ? handleReturnBuild
                    : "global::LuminaSharp.Wrapper<" + nativeRefRetType + ">.ForObject(__p)";

                return pad + "global::System.IntPtr __p = " + field + "(" + coreArgs + ");\n"
                     + pad + "return " + build + ";\n";
            }
            if (method.ReturnsVoid)
            {
                return pad + field + "(" + coreArgs + ");\n";
            }
            return pad + "return " + wrap($"{field}({coreArgs})") + ";\n";
        }

        bool hasStrings = stringParams.Count > 0;
        bool hasPins = spanParams.Count > 0 || selfPin != null;

        // The throw for a binding refused at bind time lives in a helper, since an inline throw blocks inlining.
        string unboundGuard = "if (!" + bound + ") { global::LuminaSharp.NativeBindings.ThrowUnbound(\"" + entry + "\"); }\n";

        sb.Append("        {\n");
        int indent = 12;
        sb.Append(Pad(indent)).Append(statCount);
        sb.Append(Pad(indent)).Append(unboundGuard);

        // A string argument encodes into stack scratch and only allocates when it does not fit.
        foreach ((int idx, string name) in stringParams)
        {
            sb.Append(Pad(indent)).Append("byte* __sb").Append(idx).Append(" = stackalloc byte[").Append(Utf8ScratchBytes).Append("];\n");
            sb.Append(Pad(indent)).Append("byte* __enc").Append(idx).Append(" = global::LuminaSharp.Interop.ToUtf8(").Append(name)
              .Append(", __sb").Append(idx).Append(", ").Append(Utf8ScratchBytes).Append(", out int __len").Append(idx).Append(");\n");
        }

        if (hasStrings)
        {
            sb.Append(Pad(indent)).Append("try\n").Append(Pad(indent)).Append("{\n");
            indent += 4;
        }

        // The self pointer and span arguments become stacked fixed pins around the call.
        if (selfPin != null)
        {
            sb.Append(Pad(indent)).Append(selfPin).Append('\n');
        }
        foreach ((int idx, string name, string elem) in spanParams)
        {
            sb.Append(Pad(indent)).Append("fixed (").Append(elem).Append("* __sp").Append(idx)
              .Append(" = ").Append(name).Append(")\n");
        }
        if (hasPins)
        {
            sb.Append(Pad(indent)).Append("{\n");
            sb.Append(CoreBody(indent + 4));
            sb.Append(Pad(indent)).Append("}\n");
        }
        else
        {
            sb.Append(CoreBody(indent));
        }

        if (hasStrings)
        {
            indent -= 4;
            sb.Append(Pad(indent)).Append("}\n").Append(Pad(indent)).Append("finally\n").Append(Pad(indent)).Append("{\n");
            foreach ((int idx, string _) in stringParams)
            {
                sb.Append(Pad(indent + 4)).Append("global::LuminaSharp.Interop.FreeUtf8(__enc").Append(idx).Append(", __sb").Append(idx).Append(");\n");
            }
            sb.Append(Pad(indent)).Append("}\n");
        }

        sb.Append("        }\n");

        string ns = type.ContainingNamespace.IsGlobalNamespace
            ? string.Empty
            : type.ContainingNamespace.ToDisplayString();

        var headers = new List<string>();
        var path = new List<string>();
        for (INamedTypeSymbol? container = type; container != null; container = container.ContainingType)
        {
            headers.Insert(0, TypeHeader(container));
            path.Insert(0, container.Name);
        }

        return new Model(ns, string.Join(".", path), string.Join("\n", headers), sb.ToString());
    }

    // The emitted partial must repeat the primary declaration's struct, readonly and static modifiers.
    private static string TypeHeader(INamedTypeSymbol type)
    {
        bool isStruct = type.TypeKind == TypeKind.Struct;
        string typeKeyword = isStruct ? "struct" : "class";
        string readonlyMod = isStruct && type.IsReadOnly ? " readonly" : string.Empty;
        string staticTypeMod = !isStruct && type.IsStatic ? " static" : string.Empty;
        return $"{Accessibility(type.DeclaredAccessibility)}{staticTypeMod}{readonlyMod} unsafe partial {typeKeyword} {type.Name}";
    }

    private static void Emit(SourceProductionContext spc, ImmutableArray<Model?> all)
    {
        IEnumerable<Model> models = all.Where(m => m is not null).Select(m => m!);
        foreach (Model refused in models.Where(m => m.Error is not null))
        {
            spc.ReportDiagnostic(refused.Error!);
        }
        models = models.Where(m => m.Error is null);

        foreach (IGrouping<(string Namespace, string TypePath, string TypeHeaders), Model> group in
                 models.GroupBy(m => (m.Namespace, m.TypePath, m.TypeHeaders)))
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated/>\n#nullable enable\n");

            bool hasNs = group.Key.Namespace.Length > 0;
            if (hasNs)
            {
                sb.Append("namespace ").Append(group.Key.Namespace).Append("\n{\n");
            }
            string[] headers = group.Key.TypeHeaders.Split('\n');
            foreach (string header in headers)
            {
                sb.Append("    ").Append(header).Append("\n    {\n");
            }
            foreach (Model model in group)
            {
                sb.Append(model.Member);
            }
            sb.Insert(sb.Length, "    }\n", headers.Length);
            if (hasNs)
            {
                sb.Append("}\n");
            }

            string hint = (hasNs ? group.Key.Namespace + "." : string.Empty) + group.Key.TypePath + ".NativeCall.g.cs";
            spc.AddSource(hint, SourceText.From(sb.ToString(), Encoding.UTF8));
        }
    }

    // Null when no type in the base chain has a Handle field or property, which LUM0301 refuses.
    private static string? FindHandleType(INamedTypeSymbol type, SymbolDisplayFormat fq)
    {
        for (INamedTypeSymbol? current = type; current != null; current = current.BaseType)
        {
            foreach (ISymbol member in current.GetMembers("Handle"))
            {
                ITypeSymbol? handleType = member switch
                {
                    IFieldSymbol field => field.Type,
                    IPropertySymbol property => property.Type,
                    _ => null,
                };
                if (handleType != null)
                {
                    return handleType.ToDisplayString(fq);
                }
            }
        }
        return null;
    }

    // The same sum the native side computes from its own declaration, so a drifted export fails at bind.
    private static string SignatureSum(List<string> nativeTypes)
    {
        var Widths = new List<string>();
        foreach (string Type in nativeTypes)
        {
            if (Type != "void")
            {
                Widths.Add("sizeof(" + Type + ")");
            }
        }
        return Widths.Count == 0 ? "0" : string.Join(" + ", Widths);
    }

    // A generated struct handle, or a nullable of one, which crosses as the address it views.
    private static INamedTypeSymbol? StructHandleOf(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol nullable && nullable.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
        {
            type = nullable.TypeArguments[0];
        }
        if (type is INamedTypeSymbol named && ScriptPropertyClassifier.IsStructHandle(named))
        {
            return named;
        }
        return null;
    }

    // The generated fixed pin is what makes the compiler refuse a span of a managed element type.
    private static bool TryGetSpanElement(ITypeSymbol type, SymbolDisplayFormat fq, out string elementFq)
    {
        elementFq = string.Empty;
        if (type is INamedTypeSymbol named && named.IsGenericType && named.TypeArguments.Length == 1)
        {
            string unbound = named.ConstructedFrom.ToDisplayString();
            if (unbound == "System.Span<T>" || unbound == "System.ReadOnlySpan<T>")
            {
                elementFq = named.TypeArguments[0].ToDisplayString(fq);
                return true;
            }
        }
        return false;
    }

    private static Kind Classify(ITypeSymbol type, string fqName)
    {
        if (type.SpecialType == SpecialType.System_String)
        {
            return Kind.String;
        }
        if (type.SpecialType == SpecialType.System_Boolean)
        {
            return Kind.Bool;
        }
        if (type.TypeKind == TypeKind.Struct && ScriptPropertyClassifier.IsSoftObjectReference(type))
        {
            return Kind.SoftPath;
        }
        if (type.TypeKind == TypeKind.Enum)
        {
            return Kind.Enum;
        }
        if (fqName == EntityType)
        {
            return Kind.Entity;
        }
        if (type is IArrayTypeSymbol { IsSZArray: true })
        {
            return Kind.Array;
        }
        return Kind.Pass;
    }

    private static string Accessibility(Accessibility a) => a switch
    {
        Microsoft.CodeAnalysis.Accessibility.Public => "public",
        Microsoft.CodeAnalysis.Accessibility.Internal => "internal",
        Microsoft.CodeAnalysis.Accessibility.Protected => "protected",
        Microsoft.CodeAnalysis.Accessibility.ProtectedOrInternal => "protected internal",
        Microsoft.CodeAnalysis.Accessibility.ProtectedAndInternal => "private protected",
        Microsoft.CodeAnalysis.Accessibility.Private => "private",
        _ => string.Empty,
    };
