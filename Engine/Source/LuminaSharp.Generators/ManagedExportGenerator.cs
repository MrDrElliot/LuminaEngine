using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace LuminaSharp.Generators;

// Registers each engine [ManagedExport] by name so native resolves its function pointer at bootstrap without a mirrored struct.
[Generator]
public sealed class ManagedExportGenerator : IIncrementalGenerator
{
    private const string AttributeMetadataName = "LuminaSharp.ManagedExportAttribute";

    private static readonly DiagnosticDescriptor DuplicateName = new(
        id: "LUM0304",
        title: "Duplicate [ManagedExport] name",
        messageFormat: "[ManagedExport] '{0}' is exported as '{1}', a name another method also exports, so native could resolve either one. Give each export its own name.",
        category: "LuminaSharp",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor NotStdcallEntry = new(
        id: "LUM0305",
        title: "[ManagedExport] is not a static Stdcall [UnmanagedCallersOnly] method",
        messageFormat: "[ManagedExport] '{0}' must be static and carry [UnmanagedCallersOnly(CallConvs = new[] {{ typeof(CallConvStdcall) }})], since native calls it through a Stdcall function pointer",
        category: "LuminaSharp",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private const string AttributeSource = @"// <auto-generated/>
#nullable enable
namespace LuminaSharp
{
    // Exports a static Stdcall [UnmanagedCallersOnly] method to native under Name, or the method name when unset.
    [global::System.AttributeUsage(global::System.AttributeTargets.Method)]
    internal sealed class ManagedExportAttribute : global::System.Attribute
    {
        public ManagedExportAttribute() { }
        public ManagedExportAttribute(string name) { Name = name; }
        public string? Name { get; set; }
    }
}
";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx =>
            ctx.AddSource("ManagedExportAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

        IncrementalValuesProvider<Model?> models = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeMetadataName,
            predicate: static (node, _) => node is MethodDeclarationSyntax,
            transform: static (ctx, ct) => BuildModel(ctx, ct));

        IncrementalValueProvider<ImmutableArray<Model?>> collected = models.Collect();

        context.RegisterSourceOutput(collected, static (spc, all) => Emit(spc, all));
    }

    private sealed record Model(string ExportName, string Method, string ContainingType, string Signature, Location? Where, Diagnostic? Error = null);

    private static bool IsStdcallEntry(IMethodSymbol method) =>
        method.IsStatic && method.GetAttributes().Any(a =>
            a.AttributeClass?.ToDisplayString() == "System.Runtime.InteropServices.UnmanagedCallersOnlyAttribute" &&
            a.NamedArguments.Any(n => n.Key == "CallConvs" && n.Value.Kind == TypedConstantKind.Array &&
                n.Value.Values.Any(t => (t.Value as ITypeSymbol)?.ToDisplayString() == "System.Runtime.CompilerServices.CallConvStdcall")));

    private static Model? BuildModel(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
    {
        if (ctx.TargetSymbol is not IMethodSymbol method)
        {
            return null;
        }
        if (!IsStdcallEntry(method))
        {
            return new Model("", method.Name, "", "", null, Diagnostic.Create(NotStdcallEntry, method.Locations.FirstOrDefault(), method.Name));
        }

        string exportName = method.Name;
        AttributeData attr = ctx.Attributes[0];
        if (attr.ConstructorArguments.Length == 1 && attr.ConstructorArguments[0].Value is string ctorName && ctorName.Length > 0)
        {
            exportName = ctorName;
        }
        foreach (KeyValuePair<string, TypedConstant> named in attr.NamedArguments)
        {
            if (named.Key == "Name" && named.Value.Value is string n && n.Length > 0)
            {
                exportName = n;
            }
        }

        SymbolDisplayFormat fq = SymbolDisplayFormat.FullyQualifiedFormat;

        var args = new StringBuilder();
        foreach (IParameterSymbol p in method.Parameters)
        {
            args.Append(p.Type.ToDisplayString(fq)).Append(", ");
        }
        // delegate* type arguments end with the return type (void for a void method).
        args.Append(method.ReturnsVoid ? "void" : method.ReturnType.ToDisplayString(fq));

        string containing = method.ContainingType.ToDisplayString(fq);
        return new Model(exportName, method.Name, containing, args.ToString(), method.Locations.FirstOrDefault());
    }

    private static void Emit(SourceProductionContext spc, ImmutableArray<Model?> all)
    {
        IEnumerable<Model> models = all.Where(m => m is not null).Select(m => m!);
        foreach (Model refused in models.Where(m => m.Error is not null))
        {
            spc.ReportDiagnostic(refused.Error!);
        }

        var exports = new List<Model>();
        foreach (IGrouping<string, Model> named in models.Where(m => m.Error is null).GroupBy(m => m.ExportName))
        {
            // The parts of one partial method share a symbol, so only distinct methods clash.
            List<Model> methods = named.GroupBy(m => (m.ContainingType, m.Method, m.Signature)).Select(g => g.First()).ToList();
            if (methods.Count == 1)
            {
                exports.Add(methods[0]);
                continue;
            }
            foreach (Model clash in methods)
            {
                spc.ReportDiagnostic(Diagnostic.Create(DuplicateName, clash.Where, clash.Method, clash.ExportName));
            }
        }
        exports.Sort((a, b) => System.StringComparer.Ordinal.Compare(a.ExportName, b.ExportName));

        if (exports.Count == 0)
        {
            return;
        }

        var sb = new StringBuilder();
        sb.Append(@"// <auto-generated/>
#nullable enable
namespace LuminaSharp
{
    internal static unsafe class ManagedExportTable
    {
        public static void RegisterEngineExports()
        {
");
        foreach (Model m in exports)
        {
            sb.Append("            global::LuminaSharp.ManagedExportRegistry.RegisterEngine(\"")
              .Append(m.ExportName)
              .Append("\", (global::System.IntPtr)(void*)(delegate* unmanaged[Stdcall]<")
              .Append(m.Signature).Append(">)&")
              .Append(m.ContainingType).Append('.').Append(m.Method).Append(");\n");
        }
        sb.Append("        }\n    }\n}\n");

        spc.AddSource("ManagedExports.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }
}
